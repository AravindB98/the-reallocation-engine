#!/usr/bin/env node
// build-worked-run.mjs — WORKED-RUN.src.md → WORKED-RUN.md.
// Every line `<!-- include: <path> -->` (path relative to this folder) is
// replaced by that file's exact contents in a fenced block, so the pasted
// terminal output in WORKED-RUN.md is byte-for-byte what the commands printed.
//   node assignments/submissions/salonimathure20/build-worked-run.mjs
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const src = fs.readFileSync(path.join(HERE, 'WORKED-RUN.src.md'), 'utf8');
let n = 0;
const out = src.replace(/^<!-- include: (\S+?)(?: as (\w+))? -->$/gm, (_, rel, lang = 'text') => {
  const p = path.join(HERE, rel);
  if (!fs.existsSync(p)) throw new Error(`include not found: ${rel}`);
  n++;
  const body = fs.readFileSync(p, 'utf8').replace(/\s+$/, '');
  return `<sub>\`${rel}\`</sub>\n\n\`\`\`\`${lang}\n${body}\n\`\`\`\``;
});
fs.writeFileSync(path.join(HERE, 'WORKED-RUN.md'),
  '<!-- GENERATED by build-worked-run.mjs from WORKED-RUN.src.md — edit the .src.md -->\n' + out);
console.log(`✓ WORKED-RUN.md written (${n} files inlined)`);
