#!/usr/bin/env node
// build-worked-run.mjs — WORKED-RUN.src.md → WORKED-RUN.md, pasting recorded
// terminal output verbatim so the write-up cannot drift from what actually ran.
//   node assignments/submissions/bagwe-shubham1727/build-worked-run.mjs
// Markers (paths relative to this folder), each on its own line:
//   <<<file:runs/…/x.txt>>>        the whole file
//   <<<tail:N:runs/…/x.txt>>>      its last N lines
//   <<<lines:A-B:runs/…/x.txt>>>   lines A..B (1-based, inclusive)
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const src = fs.readFileSync(path.join(HERE, 'WORKED-RUN.src.md'), 'utf8');
let n = 0;
const out = src.replace(/^<<<(file|tail|lines):(?:([\d-]+):)?([^>]+)>>>$/gm, (_, kind, arg, rel) => {
  const lines = fs.readFileSync(path.join(HERE, rel), 'utf8').replace(/\n$/, '').split('\n');
  n++;
  if (kind === 'file') return lines.join('\n');
  if (kind === 'tail') return lines.slice(-Number(arg)).join('\n');
  const [a, b] = arg.split('-').map(Number);
  return lines.slice(a - 1, b).join('\n');
});
fs.writeFileSync(path.join(HERE, "WORKED-RUN.md"), `${out}\n<!-- GENERATED by build-worked-run.mjs from WORKED-RUN.src.md: edit the source, not this file. -->\n`);
console.log(`✓ WORKED-RUN.md written (${n} transcript blocks pasted verbatim)`);
